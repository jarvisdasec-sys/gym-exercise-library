export type FoodCategory =
  | "protein"
  | "carbs"
  | "fats"
  | "vegetables"
  | "fruits"
  | "condiments"
  | "beverages"
  | "snacks";

export interface Food {
  slug: string;
  name: string;
  category: FoodCategory;
  /** human-readable common serving, e.g. "1 cup (158 g)" */
  serving: string;
  /** grams in that serving */
  grams: number;
  /** one practical coaching note */
  note: string;
  /** per 100 g */
  kcal: number;
  protein: number;
  carbs: number;
  fat: number;
  fiber: number;
  /** exact USDA FoodData Central entry used */
  usdaName: string;
  /** FoodData Central ID, null where no USDA entry exists */
  fdcId: number | null;
}

