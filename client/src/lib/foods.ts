/** Macros for an arbitrary gram amount of a food. */
export function scale(food: Food, grams: number) {
  const f = grams / 100;
  return {
    kcal: food.kcal * f,
    protein: food.protein * f,
    carbs: food.carbs * f,
    fat: food.fat * f,
    fiber: food.fiber * f,
  };
}

/** Macros for one standard serving of a food. */
export function perServing(food: Food) {
  return scale(food, food.grams);
}

export function getFood(slug: string): Food | null {
  return FOODS.find((f) => f.slug === slug) ?? null;
}

export function byCategory(category: FoodCategory): Food[] {
  return FOODS.filter((f) => f.category === category);
}

/** Share of calories from each macro, for the breakdown bars. */
export function macroSplit(m: {
  protein: number;
  carbs: number;
  fat: number;
}) {
  const p = m.protein * 4;
  const c = m.carbs * 4;
  const f = m.fat * 9;
  const total = p + c + f;
  if (total <= 0) return { protein: 0, carbs: 0, fat: 0 };
  return {
    protein: (p / total) * 100,
    carbs: (c / total) * 100,
    fat: (f / total) * 100,
  };
}
